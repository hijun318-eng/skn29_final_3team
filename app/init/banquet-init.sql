-- Banquet DB (PostgreSQL) — 연회 예약, 매출
CREATE TABLE IF NOT EXISTS banquet_bookings (
    booking_id VARCHAR(36) PRIMARY KEY,
    customer_id VARCHAR(36) NOT NULL,
    event_date DATE NOT NULL,
    event_type VARCHAR(32) DEFAULT 'WEDDING',
    guest_count INTEGER DEFAULT 0,
    status VARCHAR(16) DEFAULT 'CONFIRMED',
    is_synthetic BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS banquet_revenue (
    revenue_id VARCHAR(36) PRIMARY KEY,
    booking_id VARCHAR(36),
    revenue_date DATE NOT NULL,
    amount INTEGER DEFAULT 0,
    category VARCHAR(32) DEFAULT 'CATERING',
    is_synthetic BOOLEAN DEFAULT TRUE
);

