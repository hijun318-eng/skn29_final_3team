-- PMS DB (PostgreSQL) — 예약, 객실, 투숙
-- docker-entrypoint-initdb.d로 자동 실행

CREATE TABLE IF NOT EXISTS pms_reservations (
    reservation_id VARCHAR(36) PRIMARY KEY,
    guest_id VARCHAR(36) NOT NULL,
    stay_date DATE NOT NULL,
    room_revenue INTEGER DEFAULT 0,
    room_type VARCHAR(32) DEFAULT '',
    status VARCHAR(16) DEFAULT 'CONFIRMED',
    is_synthetic BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS pms_stays (
    stay_id VARCHAR(36) PRIMARY KEY,
    reservation_id VARCHAR(36),
    guest_id VARCHAR(36) NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE,
    room_number VARCHAR(8) DEFAULT '',
    is_synthetic BOOLEAN DEFAULT TRUE
);

